function renderSeasons() {
  const s = state.stats;
  const winners = s.titles.map(([p]) => p);
  const named = Object.keys(FIXED_SLOTS).filter((p) => winners.includes(p));
  const others = winners.filter((p) => !named.includes(p));
  $("#seasonsLegend").innerHTML = named.map((p) => `<li><span class="dot" style="--c:${colorOf(p)}"></span>${esc(p)}</li>`).join("") +
    (others.length ? `<li><span class="dot" style="--c:${NEUTRAL}"></span>Others (${esc(others.join(", "))})</li>` : "");
  const LIMIT = 10;
  const list = state.seasonsAll ? s.seasons : s.seasons.slice(0, LIMIT);
  const chart = $("#seasonsChart");
  const tag = (se) => (se.game === "eFootball" && se.event !== "eFootball" ? ' <span class="tag ef">eFootball</span>' : "");
  if (state.seasonsTable) {
    const cols = [...named, ...others];
    chart.innerHTML = `
      <div class="table-scroll"><table class="table seasons-table">
        <thead><tr><th>Tournament</th><th class="num">Titles</th>${cols.map((p) => `<th class="num">${esc(p)}</th>`).join("")}</tr></thead>
        <tbody>${list.map((se) => `<tr><td>${esc(eventName(se.event))}${tag(se)}</td><td class="num">${se.total}</td>${cols.map((p) => `<td class="num">${se.by.get(p) || "–"}</td>`).join("")}</tr>`).join("")}</tbody>
      </table></div>`;
  } else {
    chart.innerHTML = list.map((se) => {
      const parts = named.filter((p) => se.by.get(p)).map((p) => ({ label: p, count: se.by.get(p), color: colorOf(p), detail: "" }));
      const rest = others.filter((p) => se.by.get(p));
      if (rest.length) {
        parts.push({
          label: "Others",
          count: rest.reduce((n, p) => n + se.by.get(p), 0),
          color: NEUTRAL,
          detail: rest.map((p) => `${p} ${se.by.get(p)}`).join(" · "),
        });
      }
      const [topName, topCount] = [...se.by.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0];
      const name = eventName(se.event);
      return `
        <div class="season-row">
          <div class="season-name"><span class="txt" title="${esc(name)}">${esc(name)}</span>${tag(se)}</div>
          <div class="seg-bar">${parts.map((part) => {
            const label = `${part.label}: ${part.count} of ${se.total} (${pct(part.count, se.total)}%)`;
            const sub = part.detail ? `${part.detail} · ${name}` : name;
            return `<span class="seg" role="img" tabindex="0" style="flex:${part.count} 1 0;--c:${part.color}" data-tip="${esc(label)}" data-tip-sub="${esc(sub)}" aria-label="${esc(`${name}, ${label}${part.detail ? ` (${part.detail})` : ""}`)}"></span>`;
          }).join("")}</div>
          <div class="season-total"><b>${se.total}</b> ${se.total === 1 ? "title" : "titles"} · ${esc(topName)} ${topCount}</div>
        </div>`;
    }).join("");
  }
  const more = $("#seasonsMore");
  more.hidden = s.seasons.length <= LIMIT;
  more.textContent = state.seasonsAll ? "Show fewer" : `Show all ${s.seasons.length} tournaments`;
  const view = $("#seasonsView");
  view.textContent = state.seasonsTable ? "Show as chart" : "Show as table";
  view.setAttribute("aria-pressed", String(state.seasonsTable));
}

