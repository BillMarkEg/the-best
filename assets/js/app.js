function initTooltip() {
  const tip = $("#tooltip");
  const place = (x, y) => {
    const r = tip.getBoundingClientRect();
    let left = x + 14, top = y + 16;
    if (left + r.width > innerWidth - 8) left = x - r.width - 14;
    if (top + r.height > innerHeight - 8) top = y - r.height - 16;
    tip.style.left = `${Math.max(8, left)}px`;
    tip.style.top = `${Math.max(8, top)}px`;
  };
  const show = (el, x, y) => {
    tip.innerHTML = `${esc(el.dataset.tip)}${el.dataset.tipSub ? `<small>${esc(el.dataset.tipSub)}</small>` : ""}`;
    tip.hidden = false;
    place(x, y);
  };
  document.addEventListener("pointerover", (e) => {
    const el = e.target.closest?.("[data-tip]");
    if (el) show(el, e.clientX, e.clientY);
  });
  document.addEventListener("pointermove", (e) => {
    if (!tip.hidden && e.target.closest?.("[data-tip]")) place(e.clientX, e.clientY);
  });
  document.addEventListener("pointerout", (e) => {
    const el = e.target.closest?.("[data-tip]");
    if (el && !el.contains(e.relatedTarget)) tip.hidden = true;
  });
  document.addEventListener("focusin", (e) => {
    const el = e.target.closest?.("[data-tip]");
    if (!el) return;
    const r = el.getBoundingClientRect();
    show(el, r.left + Math.min(r.width / 2, 120), r.bottom);
  });
  document.addEventListener("focusout", () => { tip.hidden = true; });
  addEventListener("scroll", () => { tip.hidden = true; }, { passive: true });
}

function bindUI() {
  const resetHistory = () => { state.historyLimit = 50; renderHistory(); };
  $("#fPlayer").addEventListener("change", resetHistory);
  $("#fGame").addEventListener("change", resetHistory);
  $("#fSearch").addEventListener("input", resetHistory);
  $("#historyMore").addEventListener("click", () => { state.historyLimit += 50; renderHistory(); });
  $("#seasonsMore").addEventListener("click", () => { state.seasonsAll = !state.seasonsAll; renderSeasons(); });
  $("#seasonsView").addEventListener("click", () => { state.seasonsTable = !state.seasonsTable; renderSeasons(); });
  $("#langBtn").addEventListener("click", () => {
    setLang(isArabic() ? "en" : "ar");
    renderAll();
  });
}

/** Changes published from the dashboard show here straight away, until GitHub Pages serves them. */
function applyLive(live) {
  if (live[DATA_EF]) state.ef = normalizeEf(live[DATA_EF]);
  if (live[DATA_CHAMPS]) state.champs = normalizeChamps(live[DATA_CHAMPS]);
  if (live[DATA_CONFIG]) state.config = normalizeConfig(live[DATA_CONFIG]);
  rebuild();
  renderAll();
  toast(t("toastLive"), "ok");
}

async function boot() {
  applyStatic();
  $("#heroName").textContent = t("loading");
  initTooltip();
  initImageFallback();
  bindUI();
  try {
    const [pes, ef, champs, config] = await Promise.all([
      getJSON(DATA_PES), getJSON(DATA_EF, true), getOptionalJSON(DATA_CHAMPS), getOptionalJSON(DATA_CONFIG), loadArabicNames(),
    ]);
    state.pes = Array.isArray(pes.winners) ? pes.winners : [];
    state.ef = normalizeEf(newerPending(DATA_EF, ef) || ef);
    state.champs = normalizeChamps(newerPending(DATA_CHAMPS, champs) || champs);
    state.config = normalizeConfig(newerPending(DATA_CONFIG, config) || config);
    rebuild();
    initAnnouncements(state);
    renderAll();
    watchPending(applyLive);
  } catch (err) {
    console.error(err);
    $("#heroName").textContent = t("loadError");
    $("#heroTeam").textContent = location.protocol === "file:" ? t("fileProtocol") : String(err.message || err);
  }
}

boot();
