function renderHero() {
  const w = state.all.at(-1);
  const media = $("#heroMedia"), win = $("#heroWin"), credit = $("#heroCredit");
  if (!w) {
    $("#heroName").textContent = "No champion yet";
    return;
  }
  const s = state.stats;
  const titles = new Map(s.titles), efTitles = new Map(s.efTitles);
  $("#heroEyebrow").textContent = `Latest champion · ${w.game}`;
  $("#heroName").textContent = w.player;
  $("#heroTeam").innerHTML = `${icon("shield")}<span>${esc(teamName(w.team))}</span>`;

  const chips = [`<li class="chip">${icon("trophy")}${esc(eventName(w.event) || w.game)}</li>`];
  if (w.date) chips.push(`<li class="chip">${icon("calendar")}${esc(fmtDate(w.date))}</li>`);
  if (w.score || w.runnerUp) chips.push(`<li class="chip">Final ${esc([w.score, w.runnerUp && `v ${w.runnerUp}`].filter(Boolean).join(" "))}</li>`);
  if (w.star) chips.push(`<li class="chip gold">${icon("star")}Star player: ${esc(w.star)}</li>`);
  $("#heroChips").innerHTML = chips.join("");

  const rank = s.titles.findIndex(([p]) => p === w.player) + 1;
  const stats = [];
  if (w.game === "eFootball") stats.push(["eFootball titles", fmt(efTitles.get(w.player))]);
  stats.push(["Titles all-time", fmt(titles.get(w.player))]);
  stats.push(["All-time rank", `#${rank}`]);
  if (s.current.player === w.player && s.current.len > 1) stats.push(["Win streak", fmt(s.current.len)]);
  $("#heroStats").innerHTML = stats.map(([k, v]) => `<div><dt>${esc(k)}</dt><dd>${esc(v)}</dd></div>`).join("");

  const bg = w.cover || w.winImage;
  media.classList.toggle("is-blurred", !w.cover && !!w.winImage);
  media.innerHTML = bg ? img(bg, "", "", 'loading="eager" fetchpriority="high"') : "";
  win.hidden = !w.winImage;
  win.innerHTML = w.winImage ? `${img(w.winImage, "", `${w.player} winning with ${teamName(w.team)}`, 'loading="eager"')}<figcaption>Winning moment</figcaption>` : "";
  const url = safeUrl(w.coverCreditUrl);
  credit.innerHTML = w.cover && w.coverCredit ? `Photo: ${url ? `<a href="${esc(url)}" target="_blank" rel="noopener">${esc(w.coverCredit)}</a>` : esc(w.coverCredit)}` : "";
}

