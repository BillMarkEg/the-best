async function getJSON(url, fresh = false) {
  // "no-cache" still uses the browser's copy, but checks with GitHub first that it hasn't changed.
  const res = await fetch(fresh ? `${url}?v=${Date.now()}` : url, { cache: fresh ? "no-store" : "no-cache" });
  if (!res.ok) throw new Error(`Could not load ${url} (HTTP ${res.status})`);
  return res.json();
}
async function loadArabicNames() {
  try {
    const d = await getJSON(DATA_NAMES_AR);
    const toMap = (o) => new Map(Object.entries(o || {}).map(([k, v]) => [k.trim().toLowerCase(), String(v)]));
    state.namesAr = { players: toMap(d.players), teams: toMap(d.teams), events: toMap(d.events) };
  } catch { /* optional file: names stay as written */ }
}
function normalizeEf(data) {
  const winners = Array.isArray(data?.winners) ? data.winners.filter((w) => w && w.player && w.team) : [];
  return { updatedAt: data?.updatedAt || "", winners };
}
function assignColors(all) {
  const m = new Map();
  for (const [p, slot] of Object.entries(FIXED_SLOTS)) m.set(p, PALETTE[slot]);
  for (const w of all) if (!m.has(w.player)) m.set(w.player, NEUTRAL);
  return m;
}
const tally = (list, key) => list.reduce((m, w) => m.set(key(w), (m.get(key(w)) || 0) + 1), new Map());
const sortedDesc = (m) => [...m.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

function rebuild() {
  const pes = state.pes.map((w) => ({ ...w, game: "PES" }));
  const ef = state.ef.winners.map((w, i) => ({ ...w, game: "eFootball", efIndex: i }));
  const all = [...pes, ...ef].map((w, i) => ({ ...w, n: i + 1 }));
  const total = new Map(), efCount = new Map();
  for (const w of all) {
    total.set(w.player, (total.get(w.player) || 0) + 1);
    w.titleNo = total.get(w.player);
    if (w.game === "eFootball") {
      efCount.set(w.player, (efCount.get(w.player) || 0) + 1);
      w.efTitleNo = efCount.get(w.player);
    }
  }
  state.all = all;
  state.colors = assignColors(all);
  state.stats = computeStats(all);
}

function computeStats(all) {
  const ef = all.filter((w) => w.game === "eFootball");
  let best = { len: 0 }, run = 0;
  all.forEach((w, i) => {
    run = i > 0 && all[i - 1].player === w.player ? run + 1 : 1;
    if (run > best.len) best = { len: run, player: w.player, from: all[i - run + 1], to: w };
  });
  const seasons = new Map();
  for (const w of all) {
    const event = w.event || w.game, key = `${w.game}|${event.toLowerCase()}`;
    if (!seasons.has(key)) seasons.set(key, { event, eventAr: "", game: w.game, total: 0, by: new Map(), last: 0 });
    const s = seasons.get(key);
    s.total++;
    s.last = w.n;
    s.eventAr ||= w.eventAr || "";
    s.by.set(w.player, (s.by.get(w.player) || 0) + 1);
  }
  let haul = { count: 0 };
  for (const s of seasons.values()) for (const [p, c] of s.by) if (c > haul.count) haul = { count: c, player: p, season: s };
  const clubs = new Map();
  for (const w of all) {
    const key = teamName(w.team).toLowerCase();
    if (!clubs.has(w.player)) clubs.set(w.player, new Map());
    const m = clubs.get(w.player), cur = m.get(key) || { team: w.team, teamAr: "", count: 0 };
    cur.count++;
    cur.teamAr ||= w.teamAr || "";
    m.set(key, cur);
  }
  return {
    total: all.length,
    efTotal: ef.length,
    pesTotal: all.length - ef.length,
    titles: sortedDesc(tally(all, (w) => w.player)),
    efTitles: sortedDesc(tally(ef, (w) => w.player)),
    best,
    current: { len: run, player: all.at(-1)?.player },
    seasons: [...seasons.values()].sort((a, b) => b.last - a.last),
    haul,
    clubs,
    teams: new Set(all.map((w) => teamName(w.team).toLowerCase())).size,
  };
}

