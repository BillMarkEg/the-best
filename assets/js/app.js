/* ---------------- publishing state (used by admin.js) ---------------- */
function readPending() {
  try { return JSON.parse(localStorage.getItem(LS_PENDING) || "null"); } catch { return null; }
}
function clearPending() {
  try { localStorage.removeItem(LS_PENDING); } catch { /* storage unavailable */ }
  state.pending = false;
  $("#pendingBanner").hidden = true;
}
let watchTimer;
/** Poll the live data file until GitHub Pages serves the version we just published. */
function watchPending() {
  clearInterval(watchTimer);
  if (!state.pending) return;
  let tries = 0;
  watchTimer = setInterval(async () => {
    tries += 1;
    try {
      const live = await getJSON(DATA_EF, true);
      const p = readPending();
      if (!p || (live.updatedAt || "") >= (p.data?.updatedAt || "")) {
        clearInterval(watchTimer);
        clearPending();
        state.ef = normalizeEf(live);
        rebuild();
        renderAll();
        toast(t("toastLive"), "ok");
      }
    } catch { /* keep waiting */ }
    if (tries >= 40) clearInterval(watchTimer);
  }, 15000);
}
/** Replace the eFootball data (after a publish) and re-render everything. */
export function applyEfootball(data, { pending = false } = {}) {
  state.ef = normalizeEf(data);
  if (pending) {
    try { localStorage.setItem(LS_PENDING, JSON.stringify({ savedAt: Date.now(), data })); } catch { /* storage unavailable */ }
    state.pending = true;
  }
  rebuild();
  renderAll();
  watchPending();
}
