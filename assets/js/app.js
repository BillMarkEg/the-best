async function boot() {
  initTooltip();
  initImageFallback();
  bindUI();
  try {
    const [pes, ef] = await Promise.all([getJSON(DATA_PES), getJSON(DATA_EF, true)]);
    state.pes = Array.isArray(pes.winners) ? pes.winners : [];
    let efData = ef;
    const p = readPending();
    if (p && Date.now() - p.savedAt < 15 * 60 * 1000 && (p.data?.updatedAt || "") > (ef.updatedAt || "")) {
      efData = p.data;
      state.pending = true;
    } else if (p) {
      clearPending();
    }
    state.ef = normalizeEf(efData);
    rebuild();
    renderAll();
    watchPending();
  } catch (err) {
    console.error(err);
    $("#heroName").textContent = "Couldn't load results";
    $("#heroTeam").textContent = location.protocol === "file:"
      ? "Open the site through a web server (see README): browsers block data files on file://."
      : String(err.message || err);
  }
  import("./admin.js").then((m) => m.initAdmin()).catch((e) => console.error("Admin tools failed to load", e));
}

boot();
