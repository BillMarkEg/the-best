const autoHeadline = (w) => t("autoHeadline", { player: iso(showPlayer(w.player)), team: iso(showTeam(w)) });
function autoStory(w) {
  const parts = [];
  if (w.runnerUp || w.score) parts.push(t("storyFinal", { runnerUp: w.runnerUp && iso(showPlayer(w.runnerUp)), score: w.score && iso(w.score) }));
  parts.push(t("storyTitles", { ef: w.efTitleNo, all: w.titleNo, player: iso(showPlayer(w.player)) }));
  if (w.efIndex === 0) parts.push(t("storyFirstEra"));
  return parts.join(" ");
}

function newsCard(w, latest) {
  // Text typed by the admin may be in either script, so it picks its own direction (dir="auto");
  // generated sentences follow the page direction.
  const customHeadline = isArabic() ? w.headlineAr : w.headline;
  const customStory = isArabic() ? w.storyAr : w.story;
  const headline = customHeadline || autoHeadline(w);
  const story = customStory || autoStory(w);
  const winAlt = t("winAlt", { player: showPlayer(w.player), team: showTeam(w) });
  let media;
  if (w.cover && w.winImage) media = img(w.cover, "bg") + img(w.winImage, "fg", winAlt);
  else if (w.winImage) media = img(w.winImage, "bg blur") + img(w.winImage, "fg", winAlt);
  else if (w.cover) media = img(w.cover, "bg", showStar(w));
  else media = `<div class="placeholder">${icon("trophy")}</div>`;
  const meta = [`<span class="tag ef">${bdi(showEvent(w) || "eFootball")}</span>`];
  if (w.date) meta.push(`<span>${esc(fmtDate(w.date))}</span>`);
  if (w.competitors) meta.push(`<span>${icon("users")} ${bdi(prettyComp(w.competitors))}</span>`);
  const url = safeUrl(w.coverCreditUrl);
  const credit = w.cover && w.coverCredit
    ? `<p class="photo-credit">${esc(t("photo"))} ${url ? `<a href="${esc(url)}" target="_blank" rel="noopener">${bdi(w.coverCredit)}</a>` : bdi(w.coverCredit)}</p>`
    : "";
  return `
    <article class="card news-card${latest ? " featured" : ""}">
      <div class="news-media${w.winImage ? " has-win" : ""}">${latest ? `<span class="badge-new">${esc(t("badgeLatest"))}</span>` : ""}${media}</div>
      <div class="news-body">
        <p class="news-meta">${meta.join("")}</p>
        <h3${customHeadline ? ' dir="auto"' : ""}>${esc(headline)}</h3>
        <p class="news-text"${customStory ? ' dir="auto"' : ""}>${esc(story)}</p>
        ${showStar(w) ? `<p class="chip gold" style="align-self:flex-start;margin:0">${icon("star")}${esc(t("starChip", { star: iso(showStar(w)) }))}</p>` : ""}
        ${credit ? `<div class="news-foot">${credit}</div>` : ""}
      </div>
    </article>`;
}

