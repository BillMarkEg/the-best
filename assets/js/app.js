/* ---------------- helpers ---------------- */
const $ = (sel, root = document) => root.querySelector(sel);
const ESC = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
export const esc = (v) => String(v ?? "").replace(/[&<>"']/g, (c) => ESC[c]);
const icon = (name, cls = "") => `<svg class="icon ${cls}" aria-hidden="true"><use href="#i-${name}"/></svg>`;
const fmt = (n) => Number(n || 0).toLocaleString("en-US");
const pct = (a, b) => (b ? Math.round((a / b) * 100) : 0);
// Capitalise the first letter, but leave camel-case names like "eFootball" alone.
const capFirst = (s) => (!s || /^[a-z][A-Z]/.test(s) ? s || "" : s[0].toUpperCase() + s.slice(1));
const safeUrl = (u) => (/^https?:\/\//i.test(String(u || "")) ? String(u) : "");
export const ordinal = (n) => {
  const s = ["th", "st", "nd", "rd"], v = n % 100;
  return `${n}${s[(v - 20) % 10] || s[v] || s[0]}`;
};
export function fmtDate(d) {
  if (!d) return "";
  const t = new Date(`${d}T00:00:00`);
  return Number.isNaN(t.getTime()) ? String(d) : t.toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });
}
const ABBR = new Set(["fc", "cf", "sc", "ac", "afc", "fk", "sv", "cd", "ud", "psg", "atm"]);
/** Display name for a team: capitalises lower-case words from the sheet ("celta vigo" → "Celta Vigo"). */
export function teamName(t) {
  return String(t ?? "").trim().split(/\s+/)
    .map((w) => (ABBR.has(w.toLowerCase()) ? w.toUpperCase() : /^[a-z]/.test(w) ? capFirst(w) : w))
    .join(" ");
}
export const eventName = (e) => capFirst(String(e ?? "").trim());
const prettyComp = (c) => (String(c).trim().toLowerCase() === "all" ? "All players" : String(c));
export const initials = (name) => {
  const p = String(name ?? "?").trim().split(/\s+/);
  return (p.length > 1 ? p[0][0] + p[p.length - 1][0] : p[0].slice(0, 2)).toUpperCase();
};
const colorOf = (p) => state.colors.get(p) || NEUTRAL;
const avatar = (p, cls = "") => `<span class="avatar ${cls}" style="--c:${colorOf(p)}" aria-hidden="true">${esc(initials(p))}</span>`;
const isUrl = (p) => /^(https?:|blob:|data:)/i.test(String(p));
function img(path, cls, alt = "", extra = 'loading="lazy"') {
  const src = state.localImages.get(path) || path;
  return `<img class="${cls}" src="${esc(src)}"${isUrl(path) ? "" : ` data-path="${esc(path)}"`} alt="${esc(alt)}" ${extra} decoding="async">`;
}

